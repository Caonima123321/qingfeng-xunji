/** 合并续补点位（攀凉阿甘、成都续补等），字段口径一致，详情见 data/sites-more.js */
const { MORE_SITES } = require('./sites-more.js');
const ALL_SITES = SITES.concat(MORE_SITES);

/** 按 id 取点位 */
function findSite(id) {
  return ALL_SITES.find(function (s) {
    return String(s.id) === String(id);
  }) || null;
}

/** 按市州取点位 */
function sitesOfCity(city) {
  return ALL_SITES.filter(function (s) { return s.city === city; });
}

module.exports = {
  SITES: ALL_SITES,
  findSite: findSite,
  sitesOfCity: sitesOfCity
};
